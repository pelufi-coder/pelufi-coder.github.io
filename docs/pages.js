function renderInfoPage(lang) {
  const main = document.querySelector('main');
  const section = main.dataset.page;

  if (!section) return false;

  const copy = infoCopy[lang];
  const article = document.createElement('article');

  article.className = 'info-page';

  copy[section].forEach((text, index) => {
    const node = document.createElement(
      index === 0 ? 'h1' : index % 2 ? 'h2' : 'p'
    );

    node.textContent = text;
    article.append(node);
  });

  if (section === 'legal') {
    const heading = document.createElement('h2');

    heading.textContent = copy.owner;
    article.append(heading);

    for (const [label, value] of [
      [copy.name, legalOwner.name],
      [copy.brand, legalOwner.brand],
      [copy.location, [legalOwner.city, legalOwner.country].filter(Boolean).join(', ')],
      [copy.address, legalOwner.publicAddress],
      [copy.taxId, legalOwner.taxId]
    ]) {
      if (!value.trim()) continue;

      const row = document.createElement('p');
      const field = document.createElement('strong');

      field.textContent = label + ': ';
      row.append(field, value);
      article.append(row);
    }
  }

  const contact = document.createElement('h2');

  contact.textContent = copy.contact;

  const link = document.createElement('a');

  link.href = 'mailto:' + legalOwner.email;
  link.textContent = legalOwner.email;

  article.append(contact, link);
  main.replaceChildren(article);

  return true;
}

function updatePageMeta(lang) {
  const type = document.querySelector('main').dataset.page;
  const route = type
    ? '/' + type + '/'
    : document.querySelector('#quiz-root')
      ? '/quiz/'
      : '/';

  const title = type
    ? infoCopy[lang][type][0] + ' · PELUFI'
    : document.title;

  const desc = type
    ? infoCopy[lang][type][2]
    : infoCopy[lang][route === '/' ? 'home' : 'quiz'];

  document.title = title;
  document.querySelector('meta[name=description]').content = desc;

  for (const [key, value] of Object.entries({
    title,
    description: desc,
    url: 'https://pelufi.com' + route + '?lang=' + lang
  })) {
    document.querySelector('meta[property="og:' + key + '"]').content = value;
  }

  document.querySelector('link[rel=canonical]').href =
    'https://pelufi.com' + route + '?lang=' + lang;
}